// Usage: node tools/build.js [CODE ...]
// Merges src/<CODE>/*.js parts into data/<CODE>.js.
// Part files are CommonJS modules:
//   meta.js        module.exports = { code, name, evidence, exam, hints }
//   topics-*.js    module.exports = [ ...topics ]
//   cards-*.js     module.exports = [ ...flashcards ]
//   methods-*.js   module.exports = [ ...methods ]
//   practice-*.js  module.exports = [ ...practice questions ]
//   mocks-*.js     module.exports = [ ...mock papers ]
const fs = require('fs'), path = require('path'), vm = require('vm');
const root = path.join(__dirname, '..');
const ctx = { window: {} }; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(root, 'data/manifest.js'), 'utf8'), ctx);
const codes = process.argv.length > 2 ? process.argv.slice(2) : ctx.window.MANIFEST.map(m => m.code);
codes.forEach(code => {
  const dir = path.join(root, 'src', code);
  if (!fs.existsSync(dir)) return console.log(code + ': no src dir, skipped');
  const files = fs.readdirSync(dir).filter(f => f.endsWith('.js')).sort();
  const load = f => { const m = { exports: {} }; vm.runInNewContext(fs.readFileSync(path.join(dir, f), 'utf8'), { module: m, exports: m.exports }, { filename: f }); return m.exports; };
  const out = files.includes('meta.js') ? load('meta.js') : {};
  out.code = code;
  [['topics', 'topics'], ['cards', 'flashcards'], ['methods', 'methods'], ['practice', 'practice'], ['mocks', 'mocks']].forEach(([prefix, key]) => {
    out[key] = [];
    files.filter(f => f.startsWith(prefix + '-')).forEach(f => { const a = load(f); if (!Array.isArray(a)) throw new Error(f + ' must export an array'); out[key].push(...a); });
  });
  /* visuals.js: { topicId: diagram } is the "big picture" shown at the top of a topic */
  if (files.includes('visuals.js')) Object.entries(load('visuals.js')).forEach(([id, v]) => {
    const t = out.topics.find(x => x.id === id); if (!t) throw new Error(code + '/visuals.js: unknown topic ' + id);
    t.visual = v;
  });
  out.topics.sort((a, b) => a.priority - b.priority);
  const js = '/* GENERATED by tools/build.js from src/' + code + '. Edit the src files, not this one. */\nwindow.MODULES = window.MODULES || {};\nwindow.MODULES.' + code + ' = ' + JSON.stringify(out) + ';\n';
  fs.writeFileSync(path.join(root, 'data', code + '.js'), js);
  console.log(code + ': ' + out.topics.length + ' topics, ' + out.flashcards.length + ' cards, ' + out.methods.length + ' methods, ' + out.practice.length + ' practice, ' + out.mocks.length + ' mocks -> data/' + code + '.js (' + Math.round(js.length / 1024) + ' KB)');
});
